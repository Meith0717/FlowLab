DEFAULT_FPS = 30
WINDOW_SECONDS = 4  # history shown in the graphs, in seconds of output video
REQUIRED_COLUMNS = ("frameNumber", "compressionError", "iteration")

# Overlay layout (top-left PiP)
GRAPH_WIDTH_FRAC = 0.30  # fraction of frame width
GRAPH_HEIGHT_FRAC = 0.35  # fraction of frame height
GRAPH_MIN_SIZE = (300, 200)  # (width, height) in pixels
GRAPH_X, GRAPH_Y = 20, 20  # offset from the top-left corner
GRAPH_MARGIN = 10  # minimum gap to the right/bottom frame edge
BACKDROP_RGBA = (0, 0, 0, 0.55)  # translucent dark panel behind the graphs
COMP_COLOR = "#ff4d4d"  # compression error
ITER_COLOR = "#4dff6a"  # solver iterations


class RecordingError(Exception):
    """A problem with the recording or environment that the user can fix."""


# --------------------------------------------------------------------------
# Input loading
# --------------------------------------------------------------------------


def _natural_key(path):
    """Sort key so frame_9999.png comes before frame_10000.png."""
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", path.name)]


def load_recording(recording_dir):
    """Validate a recording directory and return (metrics DataFrame, sorted frame paths)."""
    recording_dir = Path(recording_dir)
    frames_dir = recording_dir / "frames"
    metrics_file = recording_dir / "metrics.csv"

    if not recording_dir.is_dir():
        raise RecordingError(f"Recording directory not found: {recording_dir}")
    if not frames_dir.is_dir():
        raise RecordingError(f"Frames directory not found: {frames_dir}")
    if not metrics_file.is_file():
        raise RecordingError(f"Metrics file not found: {metrics_file}")

    try:
        metrics = pd.read_csv(metrics_file)
    except Exception as e:
        raise RecordingError(f"Could not read {metrics_file}: {e}") from e

    if metrics.empty:
        raise RecordingError("No data in metrics.csv")

    missing = [c for c in REQUIRED_COLUMNS if c not in metrics.columns]
    if missing:
        raise RecordingError(
            f"metrics.csv is missing column(s): {', '.join(missing)} "
            f"(found: {', '.join(map(str, metrics.columns))})"
        )

    frame_files = sorted(frames_dir.glob("*.png"), key=_natural_key)
    if not frame_files:
        raise RecordingError(f"No PNG frames found in {frames_dir}")

    return metrics, frame_files


def _numeric_column(metrics, name):
    return pd.to_numeric(metrics[name], errors="coerce").to_numpy(dtype=float)


def _y_limits(values):
    """Fixed Y range for a whole recording: starts at 0, 5% headroom on top."""
    lo = min(0.0, float(np.nanmin(values))) if np.isfinite(values).any() else 0.0
    hi = float(np.nanmax(values)) * 1.05 if np.isfinite(values).any() else 1.0
    if not np.isfinite(hi) or hi <= lo:
        hi = lo + 1.0
    return lo, hi


def read_frames(paths, workers=4, ahead=8):
    """Yield decoded BGR frames in order (None if unreadable).

    PNG decoding runs in a few background threads, a bounded number of frames
    ahead, so it overlaps with graph rendering and encoding.
    """
    with ThreadPoolExecutor(max_workers=workers) as pool:
        pending = deque()
        remaining = iter(paths)
        for path in remaining:
            pending.append(pool.submit(cv2.imread, str(path)))
            if len(pending) >= ahead:
                break
        while pending:
            frame = pending.popleft().result()
            for path in remaining:  # top the queue back up by one
                pending.append(pool.submit(cv2.imread, str(path)))
                break
            yield frame


