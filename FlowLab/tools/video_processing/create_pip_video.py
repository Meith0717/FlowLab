def create_pip_video(recording_dir, output_file, fps=DEFAULT_FPS):
    """
    Create Picture-in-Picture video with live metrics graph.

    Args:
        recording_dir: Path to FlowLab recording directory
        output_file: Output video path
        fps (int): Output frames per second

    Raises:
        RecordingError: if the recording or environment is unusable.
    """
    metrics, frame_files = load_recording(recording_dir)

    frame_no = _numeric_column(metrics, "frameNumber")
    comp = _numeric_column(metrics, "compressionError")
    iters = _numeric_column(metrics, "iteration")
    if np.isnan(frame_no).any():
        raise RecordingError("frameNumber column contains non-numeric values")

    # Metrics row i is paired with the i-th frame file (numeric filename order).
    num_frames = min(len(metrics), len(frame_files))
    if len(metrics) != len(frame_files):
        print(
            f"Warning: {len(metrics)} metrics rows but {len(frame_files)} frame files; "
            f"using the first {num_frames}."
        )

    first_frame = cv2.imread(str(frame_files[0]))
    if first_frame is None:
        raise RecordingError(f"Could not read first frame: {frame_files[0]}")
    height, width = first_frame.shape[:2]

    # Graph size: a fraction of the frame, with a minimum, clamped to fit.
    graph_w = max(int(width * GRAPH_WIDTH_FRAC), GRAPH_MIN_SIZE[0])
    graph_h = max(int(height * GRAPH_HEIGHT_FRAC), GRAPH_MIN_SIZE[1])
    graph_w = min(graph_w, width - GRAPH_X - GRAPH_MARGIN)
    graph_h = min(graph_h, height - GRAPH_Y - GRAPH_MARGIN)
    if graph_w < 100 or graph_h < 100:
        raise RecordingError(f"Frames are too small ({width}x{height}) for the overlay")

    # Render the panel at the exact overlay size (no resizing). Scale DPI with
    # the frame so text keeps its relative size on high-resolution recordings.
    dpi = max(100, round(100 * height / 1080))

    # Frame-number step per row, so the window width stays fixed even if frameNumber skips.
    diffs = np.diff(frame_no)
    step = float(np.median(diffs)) if diffs.size else 1.0
    if step <= 0:
        step = 1.0

    # History length is defined in seconds of video, so the on-screen scroll speed
    # is the same whatever the fps.
    window = max(10, round(WINDOW_SECONDS * fps))
    overlay = MetricsOverlay(graph_w, graph_h, dpi, window, step, _y_limits(comp), _y_limits(iters))

    print("Creating PiP video...")
    print(f"   Recording:   {recording_dir}")
    print(f"   Output:      {output_file}")
    print(f"   Frames:      {num_frames}")
    print(f"   FPS:         {fps}")
    print(f"   Resolution:  {width}x{height}")
    print(f"   Graph size:  {graph_w}x{graph_h} at ({GRAPH_X}, {GRAPH_Y})")
    print(f"   Window:      {window} frames ({WINDOW_SECONDS} s of video)")
    print()

    processed = 0
    unreadable = 0
    resized = 0

    try:
        with open_writer(output_file, width, height, fps) as writer:
            for i, frame in enumerate(read_frames(frame_files[:num_frames])):
                if frame is None:
                    unreadable += 1
                    continue
                if frame.shape[:2] != (height, width):
                    frame = cv2.resize(frame, (width, height), interpolation=cv2.INTER_AREA)
                    resized += 1

                lo = max(0, i - window + 1)
                rgba = overlay.render(
                    frame_no[lo : i + 1] - frame_no[i],
                    comp[lo : i + 1],
                    iters[lo : i + 1],
                    f"Frame {frame_no[i]:.0f}  |  last {window} frames",
                )
                overlay_rgba(frame, rgba, GRAPH_X, GRAPH_Y)

                writer.write(frame)
                processed += 1

                if (i + 1) % 50 == 0 or i == num_frames - 1:
                    print(f"   Progress: {i + 1}/{num_frames} frames ({(i + 1) / num_frames * 100:.1f}%)")

            if processed == 0:
                raise RecordingError("None of the frames could be read")
            encoder = writer.name
    finally:
        overlay.close()

    if unreadable:
        print(f"Warning: {unreadable} frame(s) could not be read and were skipped.")
    if resized:
        print(f"Warning: {resized} frame(s) differed from the first frame's size and were resized.")

    size_mb = Path(output_file).stat().st_size / (1024 * 1024)
    print(f"\nSuccess! Video created: {output_file}")
    print(f"   Encoder: {encoder}")
    print(f"   Processed {processed} frames")
    print(f"   File size: {size_mb:.2f} MB")


def main(argv=None):
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Create PiP video with live metrics graph from FlowLab recording",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python create_pip_video.py /path/to/recording/
  python create_pip_video.py ~/Documents/FlowLab3D/Recordings/2026_10_06_17_55_55/ --fps 25
        """,
    )
    parser.add_argument("recording_dir", help="Path to FlowLab recording directory")
    parser.add_argument(
        "--fps",
        type=int,
        default=DEFAULT_FPS,
        help=f"Output frames per second (default: {DEFAULT_FPS})",
    )
    args = parser.parse_args(argv)
    if args.fps <= 0:
        parser.error("--fps must be a positive integer")

    # Output goes into the recording directory, named after it.
    recording_dir = Path(args.recording_dir)
    output_file = recording_dir / f"{recording_dir.resolve().name}_pip.mp4"

    try:
        create_pip_video(recording_dir, output_file, args.fps)
    except RecordingError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())