class _FfmpegWriter:
    """Pipes raw BGR frames to ffmpeg for H.264 output."""

    name = "ffmpeg (H.264)"

    def __init__(self, path, width, height, fps):
        cmd = [
            "ffmpeg", "-y", "-loglevel", "error",
            "-f", "rawvideo", "-pix_fmt", "bgr24",
            "-s", f"{width}x{height}", "-r", str(fps), "-i", "-",
            # yuv420p needs even dimensions; pad by at most one pixel if necessary
            "-vf", "pad=ceil(iw/2)*2:ceil(ih/2)*2",
            "-c:v", "libx264", "-crf", "18", "-pix_fmt", "yuv420p",
            "-movflags", "+faststart",
            str(path),
        ]  # fmt: skip
        self._err = tempfile.TemporaryFile()
        self._proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stderr=self._err)

    def _stderr(self):
        self._err.seek(0)
        return self._err.read().decode(errors="replace").strip()

    def write(self, frame):
        try:
            self._proc.stdin.write(frame.tobytes())
        except OSError as e:  # BrokenPipeError is a subclass
            self._proc.wait()
            raise RecordingError(f"ffmpeg stopped unexpectedly:\n{self._stderr()}") from e

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is not None:
            self._proc.kill()
            self._proc.wait()
            self._err.close()
            return False
        try:
            self._proc.stdin.close()
        except OSError:
            pass
        returncode = self._proc.wait()
        message = self._stderr()
        self._err.close()
        if returncode != 0:
            raise RecordingError(f"ffmpeg failed (exit code {returncode}):\n{message}")
        return False


class _OpenCvWriter:
    """Fallback when ffmpeg is unavailable: OpenCV's mp4v encoder."""

    name = "OpenCV (mp4v)"

    def __init__(self, path, width, height, fps):
        fourcc = cv2.VideoWriter_fourcc(*"mp4v")
        self._out = cv2.VideoWriter(str(path), fourcc, fps, (width, height))
        if not self._out.isOpened():
            raise RecordingError("Could not open video writer")

    def write(self, frame):
        self._out.write(frame)

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        self._out.release()
        return False


def open_writer(path, width, height, fps):
    if shutil.which("ffmpeg"):
        return _FfmpegWriter(path, width, height, fps)
    print(
        "Warning: ffmpeg not found on PATH; falling back to OpenCV's mp4v encoder "
        "(larger files, lower quality).",
        file=sys.stderr,
    )
    return _OpenCvWriter(path, width, height, fps)


