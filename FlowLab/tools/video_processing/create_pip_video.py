def _fmt(value):
    """Compact number format shared by tick labels and readouts."""
    return f"{value:.3g}" if np.isfinite(value) else "-"


_Trace = namedtuple("_Trace", "ax line head readout")


class MetricsOverlay:
    """
    Two scrolling traces on a translucent panel.

    The axes (grid, titles, tick labels) are static: they are rendered once and
    cached. Per frame, only the traces, head markers and readouts are redrawn on
    top of that cached background, so the data scrolls but nothing else moves.
    The newest sample is always at the right edge.
    """

    def __init__(self, width, height, dpi, window, step, comp_ylim, iter_ylim):
        span = (window - 1) * step  # x extent of the window, in frame-number units

        with plt.style.context("dark_background"):
            fig = plt.figure(figsize=(width / dpi, height / dpi), dpi=dpi)
            fig.patch.set_facecolor(BACKDROP_RGBA)
            fig.patch.set_visible(True)
            fig.subplots_adjust(left=0.11, right=0.97, top=0.88, bottom=0.13, hspace=0.58)
            ax_comp, ax_iter = fig.subplots(2, 1)

            specs = (
                (ax_comp, "Density Error", COMP_COLOR, comp_ylim, "default"),
                (ax_iter, "Pressure Solver Iterations", ITER_COLOR, iter_ylim, "steps-post"),
            )
            self._traces = []
            for ax, title, color, ylim, drawstyle in specs:
                ax.patch.set_visible(False)  # let the figure backdrop show through
                ax.set_xlim(-span, 0.02 * span)  # small right margin so the head dot isn't clipped
                ax.set_ylim(*ylim)
                ax.set_xticks(np.linspace(-span, 0, 5)[1:])  # fixed vertical gridlines, no labels
                ax.tick_params(axis="x", labelbottom=False, length=0)
                ax.tick_params(axis="y", labelsize=8)
                ax.yaxis.set_major_locator(MaxNLocator(nbins=4, integer=ax is ax_iter))
                ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _pos: _fmt(v)))
                ax.grid(True, alpha=0.3, linewidth=0.5)
                ax.set_title(title, loc="left", fontsize=11, color=color)

                # Everything that changes per frame is "animated": skipped by the
                # full draw below and redrawn individually in render().
                (line,) = ax.plot([], [], color=color, linewidth=2, drawstyle=drawstyle, animated=True)
                (head,) = ax.plot([], [], "o", color=color, markersize=5, animated=True)
                readout = ax.annotate(
                    "", xy=(1.0, 1.0), xycoords="axes fraction",
                    xytext=(0, 6), textcoords="offset points",
                    ha="right", va="baseline", fontsize=10, color=color, animated=True,
                )  # fmt: skip
                self._traces.append(_Trace(ax, line, head, readout))

            self._frame_ax = ax_iter
            self._frame_label = ax_iter.annotate(
                "", xy=(0.5, 0.0), xycoords="axes fraction",
                xytext=(0, -6), textcoords="offset points",
                ha="center", va="top", fontsize=9, color="0.9", animated=True,
            )  # fmt: skip

        self.fig = fig
        fig.canvas.draw()  # static parts only
        self._background = fig.canvas.copy_from_bbox(fig.bbox)

    def render(self, rel_x, comp_values, iter_values, label):
        """Return the panel as an RGBA array for the current frame.

        rel_x holds frame numbers relative to the current frame (<= 0).
        """
        canvas = self.fig.canvas
        canvas.restore_region(self._background)
        for trace, values in zip(self._traces, (comp_values, iter_values)):
            trace.line.set_data(rel_x, values)
            trace.head.set_data(rel_x[-1:], values[-1:])
            trace.readout.set_text(_fmt(values[-1]))
            for artist in (trace.line, trace.head, trace.readout):
                trace.ax.draw_artist(artist)
        self._frame_label.set_text(label)
        self._frame_ax.draw_artist(self._frame_label)
        return np.asarray(canvas.buffer_rgba())

    def close(self):
        plt.close(self.fig)


def overlay_rgba(frame, rgba, x, y):
    """Alpha-blend a straight-alpha RGBA image onto a BGR frame in place."""
    h = min(rgba.shape[0], frame.shape[0] - y)
    w = min(rgba.shape[1], frame.shape[1] - x)
    rgba = rgba[:h, :w]
    roi = frame[y : y + h, x : x + w]

    alpha = rgba[..., 3:4].astype(np.float32) / 255.0
    bgr = rgba[..., 2::-1]  # RGB -> BGR
    roi[:] = (bgr * alpha + roi * (1.0 - alpha)).astype(np.uint8)


